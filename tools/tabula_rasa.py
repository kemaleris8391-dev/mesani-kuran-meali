_FORBIDDEN_AUDIT_RES = [re.compile(p, re.UNICODE) for p in _FORBIDDEN_AUDIT_PATTERNS]


def find_forbidden_terms(text):
    """Metinde kalan geleneksel/fıkhî terimleri döndürür (Türkçe İ/I uyumlu)."""
    if not text:
        return []
    lowered = _tr_lower(text)
    found = []
    for regex in _FORBIDDEN_AUDIT_RES:
        for m in regex.finditer(lowered):
            found.append(m.group(0))
    return found


def _ci_tr_pattern(pat):
    """
    Türkçe İ/i, I/ı, Â/a, Û/u karakterlerini regex içinde güvenli kılar.
    """
    repl = {
        'i': '[İi]',
        'ı': '[Iı]',
        'ş': '[Şş]',
        'ğ': '[Ğğ]',
        'ü': '[Üü]',
        'ö': '[Öö]',
        'ç': '[Çç]',
        'a': '[AÂaâ]',
        'u': '[UÛuû]',
    }
    # Yalnızca düz metin kelimelerini saralım; regex metakarakterlerine dokunmayalım
    out = []
    in_escape = False
    for ch in pat:
        if in_escape:
            out.append(ch)
            in_escape = False
        elif ch == '\\':
            out.append(ch)
            in_escape = True
        elif ch in repl:
            out.append(repl[ch])
        else:
            out.append(ch)
    return ''.join(out)


