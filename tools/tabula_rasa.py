def purify_tabula_rasa(text):
    """
    Geleneksel/fıkhî terimleri ayıklayarak saf Tabula Rasa Türkçe metin üretir.
    """
    if not text:
        return ''
    res = text
    for regex, rep in _COMPILED_REPLACEMENTS:
        res = regex.sub(rep, res)
    return res
